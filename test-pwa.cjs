const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const root=__dirname, scope='https://fdssmartcampus.github.io/fdssmarthcampusbeta/';
const manifest=JSON.parse(fs.readFileSync(path.join(root,'manifest.webmanifest'),'utf8'));
assert.equal(new URL(manifest.start_url,scope).href,scope+'app/');
assert.equal(manifest.display,'standalone');
manifest.icons.forEach(icon=>assert(fs.existsSync(path.join(root,icon.src))));
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
assert(html.includes('rel="manifest" href="./manifest.webmanifest"'));
assert(html.includes('src="./pwa.js" defer'));
new vm.Script(fs.readFileSync(path.join(root,'pwa.js'),'utf8'));
const events={}, writes=[],deleted=[];let fail=false,claimed=false,skipped=false;
const offline=new Response('<h1>Offline</h1>',{headers:{'Content-Type':'text/html'}});
const context={URL,Request,Response,Set,Promise,self:{location:{href:scope+'sw.js'},addEventListener:(name,fn)=>events[name]=fn,clients:{claim:async()=>{claimed=true}},skipWaiting:()=>{skipped=true}},caches:{open:async()=>({addAll:async files=>writes.push(...files.map(f=>f.url)),match:async url=>url===scope+'offline.html'?offline.clone():undefined}),keys:async()=>['unrelated-site-cache','fds-campus-pwa-old'],delete:async key=>deleted.push(key)},fetch:async()=>{if(fail)throw Error('network down');return new Response('current network page')}};
vm.runInNewContext(fs.readFileSync(path.join(root,'sw.js'),'utf8'),context);
(async()=>{
 let waiting;events.install({waitUntil:p=>waiting=p});await waiting;
 assert(writes.length>=7);assert(!writes.includes(scope));assert(!writes.some(x=>/index\.html|\/auth\/|\/rest\/|reservas/.test(x)));assert(writes.every(x=>x.startsWith(scope)));assert(writes.includes(scope+'vendor/supabase.js'));
 events.activate({waitUntil:p=>waiting=p});await waiting;assert(claimed);assert.deepEqual(deleted,['fds-campus-pwa-old']);
 const request=(url,mode='cors',method='GET')=>{let response;events.fetch({request:{url,mode,method},respondWith:r=>response=r});return response};
 assert.equal(request('https://project.supabase.co/rest/v1/reservas'),undefined);
 assert.equal(request(scope+'api/reservas'),undefined);
 assert.equal(request(scope+'index.html','cors','POST'),undefined);
 assert.equal(request('https://fdssmartcampus.github.io/other-site/','navigate'),undefined);
 let response=await request(scope,'navigate');assert.equal(await response.text(),'current network page');
 fail=true;response=await request(scope+'index.html','navigate');assert((await response.text()).includes('Offline'));
 events.message({data:{type:'ACTIVATE_UPDATE'}});assert(skipped);
 console.log('PASS: manifest/subdirectory, install assets, network-only campus, offline fallback, no auth/API cache, scoped cache cleanup and explicit updates.');
})().catch(e=>{console.error(e);process.exit(1)});
